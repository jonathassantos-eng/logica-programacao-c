#include <stdio.h>

int main(){

    // Manipulação de números inteiros (int)
    int a = 10;
    int b = 3;
    int soma = a + b;
    int diferença = a - b;
    int produto = a * b;
    int quociente = a / b;

    // %d para apresentar números inteiros
    printf("Soma: %d\n", soma);
    printf("Diferença: %d\n", diferença);
    printf("Produto: %d\n", produto);
    printf("Quociente: %d\n", quociente);
    
    return 0;
}